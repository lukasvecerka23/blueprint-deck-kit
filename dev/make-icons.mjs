// Dev only: regenerates engine/src/icons.js from the Lucide package (npm pack lucide-static) and dev/icon-list.txt.
//   node dev/make-icons.mjs path/to/lucide-static/package
// Also writes plugins/blueprint-deck/skills/blueprint-deck/reference/lucide-a-l.json and lucide-m-z.json (every Lucide icon,
// for icons a diagram adds itself; in two files because the Claude plugin directory reviews files over 256 KiB by hand).
import fs from "node:fs";
import path from "node:path";

const pkg = process.argv[2];
if (!pkg) { console.error("usage: node dev/make-icons.mjs <lucide-static package dir>"); process.exit(1); }
const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const nodes = JSON.parse(fs.readFileSync(path.join(pkg, "icon-nodes.json"), "utf8"));
const version = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8")).version;
const inner = list => list.map(([tag, at]) => `<${tag} ${Object.entries(at).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");

const names = [...new Set(fs.readFileSync(path.join(root, "dev/icon-list.txt"), "utf8").split("\n")
  .filter(l => !l.startsWith("#")).flatMap(l => l.split(/\s+/)).filter(Boolean))];
const missing = names.filter(n => !nodes[n]);
if (missing.length) { console.error("not in Lucide " + version + ": " + missing.join(", ")); process.exit(1); }

// short names used by earlier diagrams keep working
const ALIASES = {
  app: "app-window", chat: "message-circle", check: "shield-check", contract: "file-text", alert: "triangle-alert", bars: "chart-bar",
  pkg: "package", dash: "layout-dashboard", pulse: "activity", flask: "flask-conical", flow: "workflow", chain: "link", chart: "chart-line",
  helm: "ship-wheel", db: "database", bucket: "archive", sync: "refresh-cw", airgap: "wifi-off", swap: "arrow-right-left", person: "user",
  phone: "smartphone", git: "git-branch", cart: "shopping-cart", card: "credit-card", grid: "layout-grid", stream: "audio-waveform", mobile: "smartphone",
  money: "banknote", queue: "rows-3", terminal: "square-terminal", filter: "funnel", home: "house",
};
for (const [a, t] of Object.entries(ALIASES)) if (!names.includes(t)) { console.error(`alias ${a} → ${t} is not bundled`); process.exit(1); }

const body = names.map(n => `  ${JSON.stringify(n)}: '${inner(nodes[n])}',`).join("\n");
const out = `/* Icons: Lucide ${version} (https://lucide.dev), ISC License, Copyright (c) Lucide Icons and Contributors.
   Generated by dev/make-icons.mjs from dev/icon-list.txt: do not edit by hand. */
const ICONS = {
${body}
};
const ICON_ALIASES = ${JSON.stringify(ALIASES)};
`;
fs.mkdirSync(path.join(root, "engine/src"), { recursive: true });
fs.writeFileSync(path.join(root, "engine/src/icons.js"), out);
const all = Object.fromEntries(Object.entries(nodes).map(([k, v]) => [k, inner(v)]));
fs.mkdirSync(path.join(root, "plugins/blueprint-deck/skills/blueprint-deck/reference"), { recursive: true });
for (const [file, test] of [["lucide-a-l.json", k => k[0] <= "l"], ["lucide-m-z.json", k => k[0] > "l"]]) {
  const part = Object.fromEntries(Object.entries(all).filter(([k]) => test(k)).sort(([x], [y]) => (x < y ? -1 : 1)));
  fs.writeFileSync(path.join(root, "plugins/blueprint-deck/skills/blueprint-deck/reference", file), JSON.stringify(part));
}
const md = `# Icons

Every diagram includes these ${names.length} [Lucide](https://lucide.dev) icons (Lucide ${version}, ISC License). Use the name in \`icon\`.

${names.map(n => "`" + n + "`").join(" · ")}

Short names from earlier versions still work: ${Object.entries(ALIASES).map(([a, t]) => "`" + a + "` → `" + t + "`").join(", ")}.

**Any other Lucide icon** (about ${Object.keys(nodes).length} in total, see lucide.dev/icons): copy its markup from \`reference/lucide-a-l.json\` or \`reference/lucide-m-z.json\` (by the name's first letter) into the
diagram's \`icons\` map, e.g. \`"icons": { "ferris-wheel": "<path d=…/>" }\`, then use \`"icon": "ferris-wheel"\`.
Brand logos are not part of Lucide; add them the same way (an inner SVG on a 24×24 grid) or as an image (\`"icon": "data:image/svg+xml;base64,…"\`).
`;
fs.writeFileSync(path.join(root, "plugins/blueprint-deck/skills/blueprint-deck/reference/icons.md"), md);
console.log(`${names.length} icons, ${Math.round(out.length / 1024)} KB → engine/src/icons.js`);
